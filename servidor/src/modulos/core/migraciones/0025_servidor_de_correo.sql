CREATE TABLE "core"."servidor_de_correo" (
	"id" boolean PRIMARY KEY DEFAULT true NOT NULL,
	"servidor" text NOT NULL,
	"puerto" integer DEFAULT 587 NOT NULL,
	"seguridad" text DEFAULT 'starttls' NOT NULL,
	"usuario" text NOT NULL,
	"contrasena_cifrada" "bytea",
	"iv" "bytea",
	"version_de_clave" smallint,
	"remitente_direccion" text NOT NULL,
	"remitente_nombre" text NOT NULL,
	"activo" boolean DEFAULT false NOT NULL,
	"ultima_prueba_en" timestamp with time zone,
	"ultima_prueba_resultado" text,
	"creado_en" timestamp with time zone DEFAULT now() NOT NULL,
	"actualizado_en" timestamp with time zone DEFAULT now() NOT NULL,
	"creado_por" uuid DEFAULT nullif(current_setting('app.usuario_id', true), '')::uuid,
	"actualizado_por" uuid DEFAULT nullif(current_setting('app.usuario_id', true), '')::uuid,
	CONSTRAINT "servidor_de_correo_fila_unica" CHECK ("core"."servidor_de_correo"."id"),
	CONSTRAINT "servidor_de_correo_servidor_largo" CHECK (char_length("core"."servidor_de_correo"."servidor") between 1 and 253),
	CONSTRAINT "servidor_de_correo_puerto_valido" CHECK ("core"."servidor_de_correo"."puerto" in (465, 587)),
	CONSTRAINT "servidor_de_correo_seguridad_valida" CHECK ("core"."servidor_de_correo"."seguridad" in ('tls_directo', 'starttls')),
	CONSTRAINT "servidor_de_correo_seguridad_del_puerto" CHECK (("core"."servidor_de_correo"."puerto" = 465) = ("core"."servidor_de_correo"."seguridad" = 'tls_directo')),
	CONSTRAINT "servidor_de_correo_usuario_largo" CHECK (char_length("core"."servidor_de_correo"."usuario") between 1 and 254),
	CONSTRAINT "servidor_de_correo_secreto_completo" CHECK (("core"."servidor_de_correo"."contrasena_cifrada" is null) = ("core"."servidor_de_correo"."iv" is null) and ("core"."servidor_de_correo"."iv" is null) = ("core"."servidor_de_correo"."version_de_clave" is null)),
	CONSTRAINT "servidor_de_correo_iv_largo" CHECK ("core"."servidor_de_correo"."iv" is null or octet_length("core"."servidor_de_correo"."iv") = 12),
	CONSTRAINT "servidor_de_correo_remitente_largo" CHECK (char_length("core"."servidor_de_correo"."remitente_direccion") between 3 and 254),
	CONSTRAINT "servidor_de_correo_remitente_nombre_largo" CHECK (char_length("core"."servidor_de_correo"."remitente_nombre") between 1 and 80),
	CONSTRAINT "servidor_de_correo_activo_con_contrasena" CHECK (not "core"."servidor_de_correo"."activo" or "core"."servidor_de_correo"."contrasena_cifrada" is not null),
	CONSTRAINT "servidor_de_correo_resultado_de_prueba_valido" CHECK ("core"."servidor_de_correo"."ultima_prueba_resultado" is null or "core"."servidor_de_correo"."ultima_prueba_resultado" in ('enviado', 'temporal', 'permanente', 'autenticacion'))
);
